#!/usr/bin/env python3
"""Run the regression and merge functional coverage.

  scripts/regress.py                  full regression, both memory types
  scripts/regress.py --mem SDR        one memory type
  scripts/regress.py --quick          one seed per test (used in CI)

Writes docs/coverage_report.md and exits non-zero if any test fails or
functional coverage is below 100%.
"""
import argparse
import json
import re
import sys
import time
from pathlib import Path

import run_sim

ROOT = run_sim.ROOT
TESTS = ["SmokeTest", "RandomTest", "RowThrashTest", "BankPingPongTest",
         "TurnaroundTest", "IdleTest", "FillTest", "ResetTest"]

# (config, tests, seeds, transactions per test)
PLAN = {
    "SDR": [
        ("default",  TESTS, 6, 20_000),
        ("100mhz",   TESTS, 3, 20_000),
        ("143mhz",   TESTS, 6, 20_000),
        ("storm",    TESTS, 6, 20_000),
        ("storm143", TESTS, 3, 20_000),
        ("fullinit", ["SmokeTest", "ResetTest"], 1, 2_000),
    ],
    "DDR3": [
        ("default",  TESTS, 6, 20_000),
        ("storm",    TESTS, 6, 20_000),
        ("fullinit", ["SmokeTest"], 1, 2_000),
    ],
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mem", choices=["SDR", "DDR3"])
    ap.add_argument("--quick", action="store_true")
    a = ap.parse_args()

    raw = ROOT / "coverage_raw"
    raw.mkdir(exist_ok=True)
    for f in raw.glob("*.json"):
        f.unlink()

    rows, failed, txns = [], [], 0
    t0 = time.time()
    for mem in ([a.mem] if a.mem else ["SDR", "DDR3"]):
        for config, tests, seeds, n in PLAN[mem]:
            if a.quick:
                seeds, n = 1, min(n, 3_000)
            for test in tests:
                for seed in range(1, seeds + 1):
                    cov_file = raw / f"{mem}_{config}_{test}_{seed}.json"
                    xml = run_sim.run(mem, test, seed, n, config, cov_file=str(cov_file), quiet=True)
                    ok = run_sim.passed(xml)
                    log = (ROOT / "sim_build" / f"{mem}_{config}" / f"{test}_{seed}.log").read_text()
                    m = re.search(r"writes=(\d+) reads=(\d+)", log)
                    done = int(m.group(1)) + int(m.group(2)) if m else 0
                    txns += done
                    rows.append((mem, config, test, seed, done, ok))
                    if not ok:
                        failed.append(f"{mem} {config} {test} seed {seed}")
                    print(f"{'PASS' if ok else 'FAIL'}  {mem:4} {config:9} {test:17} seed {seed}  {done} txns",
                          flush=True)

    # merge coverage per memory type
    merged = {}
    for f in sorted(raw.glob("*.json")):
        d = json.loads(f.read_text())
        bins = merged.setdefault(d["mem_type"], {})
        for k, v in d["bins"].items():
            bins[k] = bins.get(k, 0) + v

    lines = ["# Functional coverage report", "",
             f"Generated by `scripts/regress.py`{' --quick' if a.quick else ''}.", "",
             f"- Tests run: {len(rows)} ({len(rows) - len(failed)} passed, {len(failed)} failed)",
             f"- Read and write transactions checked: {txns:,}",
             f"- Wall time: {time.time() - t0:.0f} s", ""]
    all_full = True
    for mem, bins in merged.items():
        hit = sum(1 for v in bins.values() if v)
        pct = 100.0 * hit / len(bins)
        all_full &= hit == len(bins)
        lines += [f"## {mem}: {hit} of {len(bins)} bins ({pct:.1f}%)", ""]
        groups = {}
        for k, v in bins.items():
            groups.setdefault(k.split(".")[0], []).append((k, v))
        lines += ["| Group | Bins | Hit |", "|---|---|---|"]
        for g, items in groups.items():
            lines.append(f"| {g} | {len(items)} | {sum(1 for _, v in items if v)} |")
        holes = [k for k, v in bins.items() if not v]
        lines += ["", "Holes: " + (", ".join(f"`{h}`" for h in holes) if holes else "none"), ""]
        lines += ["<details><summary>All bins</summary>", "", "| Bin | Hits |", "|---|---|"]
        lines += [f"| `{k}` | {v} |" for k, v in bins.items()]
        lines += ["", "</details>", ""]
    if failed:
        lines += ["## Failures", ""] + [f"- {f}" for f in failed]
    (ROOT / "docs" / "coverage_report.md").write_text("\n".join(lines) + "\n")
    (ROOT / "coverage_raw" / "merged.json").write_text(json.dumps(merged, indent=1))

    print(f"\n{len(rows) - len(failed)}/{len(rows)} tests passed, {txns:,} transactions")
    for mem, bins in merged.items():
        holes = [k for k, v in bins.items() if not v]
        print(f"{mem}: {100.0 * (len(bins) - len(holes)) / len(bins):.1f}% functional coverage"
              + (f", holes: {holes}" if holes else ""))
    sys.exit(1 if failed or not all_full else 0)


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    main()
